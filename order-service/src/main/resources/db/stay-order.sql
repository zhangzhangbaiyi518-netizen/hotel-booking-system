CREATE TABLE IF NOT EXISTS stay_order (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    request_id VARCHAR(36) NULL,
    inventory_held TINYINT NOT NULL DEFAULT 0,
    hotel_id BIGINT NOT NULL,
    room_type_id BIGINT NOT NULL,
    hotel_name VARCHAR(255) NOT NULL,
    hotel_address VARCHAR(500),
    hotel_phone VARCHAR(50),
    room_name VARCHAR(255) NOT NULL,
    capacity INT,
    description VARCHAR(2000),
    amount DECIMAL(12,2) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_PAYMENT',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_deadline DATETIME(3) NULL,
    paid_time TIMESTAMP NULL,
    check_in_time DATETIME NULL,
    check_out_time DATETIME NULL,
    room_number VARCHAR(3) NULL,
    refund_request_time DATETIME NULL,
    refund_time DATETIME NULL,
    refund_reason VARCHAR(100) NULL,
    refund_deleted TINYINT NOT NULL DEFAULT 0,
    cancelled_time DATETIME NULL,
    UNIQUE KEY uk_stay_order_request (user_id, request_id),
    INDEX idx_stay_order_inventory (inventory_held, status, check_out_time, room_type_id),
    INDEX idx_stay_order_user_status (user_id, status)
) DEFAULT CHARSET=utf8mb4;
